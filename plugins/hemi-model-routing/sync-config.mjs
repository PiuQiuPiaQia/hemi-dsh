/** Keep installed and built-in native role configuration aligned with their owning sources. */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../../', import.meta.url))
const banner = '# Generated by plugins/hemi-model-routing/sync-config.mjs; edit the owning source.\n'

/**
 * Check generated configuration, or write it when explicitly requested by the maintainer.
 * @param {boolean} write - true regenerates files; false rejects stale generated configuration.
 */
export function syncConfig(write) {
  const read = path => readFileSync(resolve(root, path), 'utf8')
  const roles = read('packages/hemi/routing/roles.patch.yml')
  const standard = read('packages/bundle/web-app/presets/standard.patch.yml')
    .replace(/^#.*\n/gm, '')
    .replace('- insert:\n    - id: preset-standard\n', '- id: preset-standard\n')
    .replace(/^    /gm, '')
    .replace(/^[ ]*# Hemi fork addition: cross-session memory stores and tools\.\n[ ]*- id: hemi-memory\n[ ]*name: '@deepseek-ai\/dsh-hemi-memory'\n/m, '')
  const outputs = new Map([
    ['packages/bundle/web-app/presets/hemi-roles.patch.yml', roles],
    ['plugins/hemi-model-routing/roles.patch.yml', roles],
    ['plugins/hemi-model-routing/standard.patch.yml', standard],
  ])
  for (const [path, body] of outputs) {
    const expected = banner + body
    if (write) writeFileSync(resolve(root, path), expected)
    else if (read(path) !== expected) throw new Error(`Stale ${path}; run node plugins/hemi-model-routing/sync-config.mjs --write`)
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) syncConfig(process.argv.includes('--write'))
